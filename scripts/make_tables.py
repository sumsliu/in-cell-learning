def _real_recall(d):
    """Recall on the 507 real probes, composition excluded -- the headline
    number; composition is reported in its own table against a ceiling."""
    k = _kinds(d)
    n = d.get("probe_counts") or {kk: {"probes": v}
                                  for kk, v in PROBE_COUNTS.items()}
    if not k:
        return d["recall"]["merged"]
    tot = hit = 0
    for kind, rec in k.items():
        if kind == "composition":
            continue
        c = n.get(kind, {}).get("probes", 0)
        tot += c
        hit += rec * c
    return hit / tot if tot else d["recall"]["merged"]



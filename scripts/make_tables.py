def capacity_cellfill_table():
    pts = [("1{,}000", ["exp10_qil_r64_qwen3-1.7b", "exp30_qil_r64_s1",
                        "exp30_qil_r64_s2"]),
           ("3{,}000", ["exp73_cellfill_3000"]),
           ("10{,}000", ["exp52_cellfill_10k"]),
           ("30{,}000", ["exp73_cellfill_30000"]),
           ("100{,}000", ["exp53_cellfill_100k"])]
    rows = []
    for label, stems in pts:
        ds = [d for d in (load(s) for s in stems) if d]
        if not ds:
            continue
        n = ds[0]["config"]["n_facts"]
        rec = [d["recall"]["merged"] for d in ds]
        absorbed = [r * n for r in rec]
        lam = [d["ppl_lambada"]["merged"] / d["ppl_lambada"]["anchor_fp32"]
               for d in ds if d.get("ppl_lambada", {}).get("anchor_fp32")]
        rows.append((label, rec, absorbed, lam, [d["merge"]["saturation"] for d in ds],
                     [d["minutes"] for d in ds]))
    if len(rows) < 2:
        return None
    out = ["% GENERATED by scripts/make_tables.py -- do not edit by hand",
           "\\begin{tabular}{lrrrrr}", "\\toprule",
           "facts & recall & absorbed & LAMBADA ratio & saturation & min \\\\",
           "\\midrule"]
    for label, rec, absorbed, lam, sat, mins in rows:
        m, sd, k = agg(rec)
        out.append(f"{label} & {fmt(m, sd, k, pct=True, nd=1)} & "
                   f"{st.mean(absorbed):,.0f} & "
                   + (f"{st.mean(lam):.2f}" if lam else "--")
                   + f" & {100 * st.mean(sat):.2f}\\% & {st.mean(mins):.0f} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out)



def _energy_share(stats):
    """Fraction of the fill energy landing in each module type."""
    groups = {"q/k/v/o (attention)": ["q_proj", "k_proj", "v_proj", "o_proj"],
              "gate/up": ["gate_proj", "up_proj"], "down": ["down_proj"]}
    tot = sum(v["fill_energy"] for v in stats.values())
    share = {}
    for g, keys in groups.items():
        share[g] = sum(v["fill_energy"] for n, v in stats.items()
                       if any(n.endswith(k) for k in keys)) / tot if tot else 0
    return share



#!/usr/bin/env python
"""Generate the paper's result tables from the archived JSONs.

Typed tables drift: an earlier draft quoted a capacity exponent its own
figure did not produce, and mixed rehearsal fractions inside one comparison.
Everything downstream of this script is therefore computed, and every cell
carries the seed count it was averaged over.

  python scripts/make_tables.py            # print LaTeX
  python scripts/make_tables.py --write     # write paper/tables/*.tex
"""

from __future__ import annotations

import argparse
import json
import sys
import statistics as st
from pathlib import Path

R = Path("results")
BITS_PER_FACT = 11.9  # probed attributes only (city, job, company)

# row label -> (files, which stage to read)
#   'merged' = after clip-merge / after the bounded fill is materialized
#   'heal'   = after projected dense healing (or, for dense-only runs, the
#              projected dense training itself)
ROWS = [
    ("A: clip-merge", "projected",
     ["exp1c_replay10_qwen3-1.7b_r16_e24", "exp1c_s1", "exp1c_s2"], "merged"),
    ("CellFill $r{=}16$", "structural",
     ["exp16_qil_r16_replay10", "exp31_qil_r16_s1", "exp31_qil_r16_s2"],
     "merged"),
    ("A+: clip-merge $\\to$ heal", "projected",
     ["exp1c_replay10_qwen3-1.7b_r16_e24", "exp1c_s1", "exp1c_s2"], "heal"),
    ("CellFill $r{=}64$", "structural",
     ["exp10_qil_r64_qwen3-1.7b", "exp30_qil_r64_s1", "exp30_qil_r64_s2"],
     "merged"),
    ("B: projected dense", "projected",
     ["exp18_b_replay10_s0", "exp18_b_replay10_s1"], "heal"),
    ("B: projected dense", "projected",
     ["exp3_dense_qwen3-1.7b_e24", "exp3_s1", "exp3_s2"], "heal"),
    ("unconstrained dense", "none",
     ["exp4_free_qwen3-1.7b_e24", "exp4_free_s1", "exp4_free_s2"], "heal"),
]


def load(stem):
    p = R / f"{stem}.json"
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text())
    except json.JSONDecodeError:
        # a truncated archive is a defect to surface, not one to crash on
        print(f"[warn] {p.name} is not readable JSON; treated as absent")
        return None


def cell(d, stage, field):
    """field in {recall, wiki, lam}; returns None when absent."""
    if d is None:
        return None
    if stage == "heal":
        h = d.get("heal") or {}
        return {"recall": h.get("recall"), "wiki": h.get("ppl"),
                "lam": h.get("ppl_x")}[field]
    return {"recall": d["recall"].get("merged"),
            "wiki": d["ppl"].get("merged"),
            "lam": (d.get("ppl_lambada") or {}).get("merged")}[field]


def agg(vals):
    vals = [v for v in vals if v is not None]
    if not vals:
        return None, None, 0
    if len(vals) == 1:
        return vals[0], None, 1
    return st.mean(vals), st.stdev(vals), len(vals)


def fmt(mean, sd, n, pct=False, nd=2):
    if mean is None:
        return "---"
    scale = 100 if pct else 1
    unit = "\\%" if pct else ""
    if sd is None:
        return f"{mean * scale:.{nd}f}{unit}"
    return f"${mean * scale:.{nd}f}\\!\\pm\\!{sd * scale:.{nd}f}${unit}"


def violations(stems):
    tot = 0
    for s in stems:
        d = load(s)
        if d and (d.get("heal") or {}).get("invariance_violations"):
            tot += d["heal"]["invariance_violations"]
    return tot


def frontier_table():
    anchor = load("exp1c_s1")
    a_wiki = anchor["ppl"]["anchor_fp32"]
    a_lam = (anchor.get("ppl_lambada") or {}).get("anchor_fp32")
    o_wiki = anchor["ppl"]["original_fp32"]
    o_lam = (anchor.get("ppl_lambada") or {}).get("original_fp32")

    out = [
        "% GENERATED by scripts/make_tables.py -- do not edit by hand",
        "\\begin{tabular}{llccccrc}",
        "\\toprule",
        "method & invariance & reh. & recall & WikiText-2 & LAMBADA ppl$\\downarrow$ &"
        "bits/pt & seeds \\\\",
        "\\midrule",
        f"4-bit anchor & (reference) & --- & --- & {a_wiki:.2f} & "
        f"{a_lam:.2f} & --- & --- \\\\",
        f"original fp32 & (reference) & --- & --- & {o_wiki:.2f} & "
        f"{o_lam:.2f} & --- & --- \\\\",
        "\\midrule",
    ]
    for label, inv, stems, stage in ROWS:
        ds = [load(s) for s in stems]
        rs = [cell(d, stage, "recall") for d in ds]
        lams = [cell(d, stage, "lam") for d in ds]
        r = agg(rs)
        w = agg([cell(d, stage, "wiki") for d in ds])
        lam = agg(lams)
        inv_s = {"structural": "\\checkmark\\ (structural)",
                 "projected": "\\checkmark", "none": "$\\times$"}[inv]
        seeds = f"{r[2]}" + (f"/{lam[2]}" if lam[2] != r[2] else "")
        # Knowledge bought per point of cross-domain perplexity given up.
        # Computed PER SEED and averaged: the prose and the ledger quote
        # mean +/- std over seed-wise ratios (918+/-183, 1126+/-205, ...),
        # and a ratio of means is a different estimator that disagreed with
        # them by up to 4% in the same table.
        effs = [ri * 1000 * BITS_PER_FACT / (li - a_lam)
                for ri, li in zip(rs, lams)
                if ri is not None and li is not None and li > a_lam]
        eff = "---"
        if effs:
            em, es, en = agg(effs)
            eff = (f"${em:.0f}\\!\\pm\\!{es:.0f}$" if en > 1
                   else f"{em:.0f}")
        reh = {str((d.get("config") or {}).get("replay_frac"))
               for d in ds if d}
        reh_s = "/".join(sorted(reh)) if reh else "---"
        out.append(
            f"{label} & {inv_s} & {reh_s} & {fmt(*r, pct=True, nd=1)} & "
            f"{fmt(*w)} & {fmt(*lam)} & {eff} & {seeds} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out)


def config_table():
    keys = [("model", "base model"), ("n_facts", "facts"),
            ("epochs", "epochs"), ("rank", "LoRA rank"),
            ("lr", "learning rate"), ("bs", "batch size"),
            ("replay_frac", "fresh rehearsal fraction"),
            ("margin", "cell margin"), ("radius", "radius $\\rho$"),
            ("heal_epochs", "healing epochs"), ("heal_lr", "healing lr"),
            ("tanh_scale", "CellFill gain $s$")]
    seen: dict[str, set] = {k: set() for k, _ in keys}
    # results/ also holds runs belonging to other manuscripts. Restricting this
    # sweep to the manifest's curated list was tried and is worse: the manifest
    # omits the capacity sweeps, so the table then under-reports knobs the
    # paper does discuss. Instead the families that belong to other papers are
    # named and excluded, so this table stays a description of the range THIS
    # paper explored rather than of everything the repository has ever run.
    OTHER_PAPERS = ("exp48_moe", "exp91_", "medgemma", "clinic", "vignette",
                    "vigmix", "medbench", "revbrand", "kinds_", "rel_clinic",
                    "years_", "intent_", "skill_", "fed_")
    for p in sorted(R.glob("*.json")):
        if any(p.stem.startswith(x) or x in p.stem for x in OTHER_PAPERS):
            continue
        try:
            cfg = json.loads(p.read_text()).get("config") or {}
        except json.JSONDecodeError:
            print(f"[warn] {p.name} is not readable JSON; skipped")
            continue
        for k, _ in keys:
            if k in cfg and cfg[k] is not None:
                seen[k].add(str(cfg[k]))
    out = ["% GENERATED by scripts/make_tables.py -- do not edit by hand",
           "\\begin{tabular}{l p{0.68\\linewidth}}", "\\toprule",
           "hyperparameter & values used \\\\", "\\midrule"]
    for k, label in keys:
        vals = sorted(seen[k], key=lambda s: (len(s), s))
        if not vals:
            continue
        shown = ", ".join(v.replace("Qwen/", "").replace("_", "\\_")
                          for v in vals[:6])
        if len(vals) > 6:
            shown += ", \\dots"
        out.append(f"{label} & {shown} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out)


def lora_real_table():
    """LoRA against CellFill on the real corpus and a published anchor.

    Three seeds each, same rank, rehearsal, epochs and probes; each method at
    its own best learning rate, and both at 1e-3 so the failure mode shows.
    The unmerged LoRA column is there because "just serve the adapter" is the
    honest null hypothesis, and it has a cost of its own.
    """

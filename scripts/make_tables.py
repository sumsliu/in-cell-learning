def stability_table():
    """exp26: the matched parameterization x learning-rate sweep.

    Same model, same seed, same rank, same rehearsal, same epochs -- the only
    differences are the parameterization and the learning rate. This is the
    controlled version of the Mistral anecdote: LoRA's usable learning rate
    is bounded by divergence, CellFill's by saturation, and saturation is a
    soft ceiling while divergence is a cliff.
    """
    CELLS = [
        ("$10^{-3}$", "LoRA $\\to$ clip-merge", "exp26_lora_lr1e-3"),
        ("$10^{-3}$", "CellFill", "exp26_cellfill_lr1e-3"),
        ("$3\\times10^{-3}$", "LoRA $\\to$ clip-merge", "exp26_lora_lr3e-3"),
        ("$3\\times10^{-3}$", "CellFill", "exp26_cellfill_lr3e-3"),
    ]
    out = ["% GENERATED by scripts/make_tables.py -- do not edit by hand",
           "\\begin{tabular}{llrrrrl}", "\\toprule",
           "lr & parameterization & \\multicolumn{2}{c}{perplexity} & "
           "recall & LAMBADA ppl$\\downarrow$ & bound engaged \\\\",
           "& & unmerged & served & & & \\\\", "\\midrule"]
    for i, (lr, param, stem) in enumerate(CELLS):
        d = load(stem)
        if d is None:
            continue
        if i == 2:
            out.append("\\midrule")
        ppl, L = d["ppl"], (d.get("ppl_lambada") or {})
        served = ppl.get("merged")
        # CellFill trains in place: there is no unmerged stage to report.
        raw = ppl.get("adapter")
        raw_s = f"{raw:,.2f}" if raw is not None else "---"
        mg = d.get("merge") or {}
        if mg.get("clipped_frac") is not None:
            eng = f"{mg['clipped_frac']:.1%} clipped".replace("%", "\\%")
        elif mg.get("saturation") is not None:
            eng = f"{mg['saturation']:.1%} saturated".replace("%", "\\%")
        else:
            eng = "---"
        out.append(
            f"{lr} & {param} & {raw_s} & {served:,.2f} & "
            f"{d['recall']['merged']*100:.1f}\\% & {L.get('merged', 0):,.2f} "
            f"& {eng} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out)


def real_corpus_table(stem="exp41_real8_final"):
    """Real knowledge, per domain, against the floor each domain actually has.

    The floors span two orders of magnitude here -- 28 Formula One races share
    five winners, so 20% in sports is guessing, while 20% in medicine or
    lottery would be a result. Reporting recall without the matching floor
    would let the reader average them.
    """
    d = load(stem)
    if d is None or not d.get("probe_counts"):
        return None
    counts = d["probe_counts"]
    merged = (d["recall"] or {}).get("merged_by_kind") or {}
    anchor = (d["recall"] or {}).get("anchor_by_kind") or {}
    nice = {"lottery": "lottery (Powerball)", "medicine": "medicine (FDA)",
            "technology": "technology (launches)", "sports": "sports (F1)",
            "awards": "awards (Abel/Fields)", "film": "film (Oscars)"}
    out = ["% GENERATED by scripts/make_tables.py -- do not edit by hand",
           "\\begin{tabular}{lrrrr}", "\\toprule",
           "domain & probes & guess floor & base model & after injection \\\\",
           "\\midrule"]
    for k in sorted(counts, key=lambda k: -counts[k]["probes"]):
        c = counts[k]
        a = anchor.get(k)
        out.append(
            f"{nice.get(k, k)} & {c['probes']} & {c['floor']*100:.1f}\\% & "
            f"{(a * 100 if a is not None else 0):.1f}\\% & "
            f"{merged.get(k, 0)*100:.1f}\\% \\\\")
    tot_p = sum(c["probes"] for c in counts.values())
    out += ["\\midrule",
            f"all & {tot_p} & --- & "
            f"{(d['recall'].get('anchor_fp32') or 0)*100:.1f}\\% & "
            f"{(d['recall'].get('merged') or 0)*100:.1f}\\% \\\\",
            "\\bottomrule", "\\end{tabular}"]
    return "\n".join(out)


def baseline_table():
    """MEMIT and GRACE against CellFill, on the same facts and the same ruler.

    The comparison is asymmetric on purpose and the table says so. The editors
    take (prompt, target) pairs, so under "verbatim" they are handed the probe
    prompts themselves and are scored on exactly what was written; CellFill is
    never given that condition. Under "generalize" only one probe kind is
    edited and all three are scored, which is the condition CellFill is always
    in. The last two columns are where the methods differ in kind: whether the
    released 4-bit file survives, and whether anything is added at inference.
    """
    rows = [
        ("MEMIT, verbatim", "baseline_memit_verbatim", "no", "no"),
        ("MEMIT, generalize", "baseline_memit_generalize", "no", "no"),
        ("GRACE, verbatim", "baseline_grace_verbatim", "yes", "codebook"),
        ("GRACE, generalize", "baseline_grace_generalize", "yes", "codebook"),
        ("CellFill $r{=}64$, 1 phrasing", "exp42_real1_cellfill", "yes", "no"),
        ("CellFill $r{=}64$, 4 phrasings", "exp41_real8_final", "yes", "no"),
    ]
    loaded = [(load(st), lab, art, inf) for lab, st, art, inf in rows]
    if not any(d for d, *_ in loaded):
        return None
    out = ["% GENERATED by scripts/make_tables.py -- do not edit by hand",
           "\\begin{tabular}{lrrrll}", "\\toprule",
           "method & recall & WikiText-2 & LAMBADA ppl$\\downarrow$ & artifact & at inference"
           " \\\\", "\\midrule"]
    for d, lab, art, inf in loaded:
        if d is None:
            continue
        if "recall" in d and isinstance(d["recall"], dict):
            rec = d["recall"].get("merged")
            wik = d["ppl"].get("merged")
            lam = (d.get("ppl_lambada") or {}).get("merged")
        else:
            rec, wik, lam = (d.get("recall"), d.get("ppl_wikitext"),
                             d.get("ppl_lambada"))
        out.append(f"{lab} & {rec*100:.1f}\\% & {wik:.2f} & "
                   f"{lam:.2f} & {art} & {inf} \\\\")
    out += ["\\bottomrule", "\\end{tabular}"]
    return "\n".join(out)


